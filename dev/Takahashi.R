sparseinv2 <- function (n, Lp, Li, Lx, d, Up, Uj, Ux, Zp, Zi) {
  .Call(`_sparseinv_sparseinv2`, n, Lp, Li, Lx, d, Up, Uj, Ux, Zp, Zi)
}

.sparseinv_wrapper <- function(L, d, U, Zpattern) {
  n <- nrow(L)
  Lp <- L@p
  Li <- L@i
  Lx <- L@x
  Up <- U@p
  Uj <- U@i
  Ux <- U@x
  Zpatp <- Zpattern@p
  Zpati <- Zpattern@i
  znz = Zpatp[n + 1]
  X <- sparseinv2(n = as.integer(n), Lp = as.integer(Lp), 
                  Li = as.integer(Li), Lx = as.double(Lx), d = as.double(d), 
                  Up = as.integer(Up), Uj = as.integer(Uj), Ux = as.double(Ux), 
                  Zp = as.integer(Zpatp), Zi = as.integer(Zpati))
  Z <- sparseMatrix(p = Zpatp, i = Zpati, x = X, index1 = F)
  return(Z)
}

Takahashi_Davis <- function(L) {
  n <- nrow(L)
  d <- diag(L)
  L <- tril(L %*% Diagonal(x = 1/d), -1)
  d <- d^2
  D <- Diagonal(x = d)
  dp <- diff(L@p)
  jj <- rep(seq_along(dp), dp)
  Zpattern <- sparseMatrix(c(L@i + 1, jj, 1:n), c(jj, L@i + 1, 1:n))
  Z <- .sparseinv_wrapper(L, d, L, Zpattern)
  return(Z)
}

